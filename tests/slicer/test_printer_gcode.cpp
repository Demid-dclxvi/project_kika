TriangleMesh box(double a, double b, double c, double x = 0, double y = 0, double z = 0) {
  TriangleMesh m;
  for (int i = 0; i < 8; ++i)
    m.vertices.push_back({x + ((i & 1) ? a : 0.0), y + ((i & 2) ? b : 0.0), z + ((i & 4) ? c : 0.0)});
  m.triangles = {{0, 2, 1}, {1, 2, 3}, {4, 5, 6}, {5, 7, 6}, {0, 1, 4}, {1, 5, 4},
                 {2, 6, 3}, {3, 6, 7}, {0, 4, 2}, {2, 4, 6}, {1, 3, 5}, {3, 7, 5}};
  return m;
}

std::vector<std::string> lines_of(const std::string& text) {
  std::vector<std::string> out;
  std::istringstream in(text);
  for (std::string l; std::getline(in, l);) out.push_back(l);
  return out;
}

std::size_t count(const std::string& text, const std::string& what) {
  std::size_t n = 0;
  for (std::size_t p = text.find(what); p != std::string::npos; p = text.find(what, p + what.size())) ++n;
  return n;
}

std::optional<double> word(const std::string& l, char c) {
  for (std::size_t i = 0; i + 1 < l.size(); ++i)
    if (l[i] == c && (i == 0 || l[i - 1] == ' ')) return std::stod(l.substr(i + 1));
  return std::nullopt;
}

std::string unbase64(const std::string& s) {
  auto val = [](char c) -> int {
    if (c >= 'A' && c <= 'Z') return c - 'A';
    if (c >= 'a' && c <= 'z') return c - 'a' + 26;
    if (c >= '0' && c <= '9') return c - '0' + 52;
    if (c == '+') return 62;
    if (c == '/') return 63;
    return -1;
  };
  std::string out;
  int buf = 0, bits = 0;
  for (char c : s) {
    const int v = val(c);
    if (v < 0) continue;
    buf = (buf << 6) | v;
    bits += 6;
    if (bits >= 8) {
      bits -= 8;
      out.push_back(static_cast<char>((buf >> bits) & 0xFF));
    }
  }
  return out;
}

std::uint32_t be32(const std::string& s, std::size_t p) {
  return (static_cast<std::uint32_t>(static_cast<unsigned char>(s[p])) << 24) |
         (static_cast<std::uint32_t>(static_cast<unsigned char>(s[p + 1])) << 16) |
         (static_cast<std::uint32_t>(static_cast<unsigned char>(s[p + 2])) << 8) | static_cast<unsigned char>(s[p + 3]);
}

TriangleMesh on_bed(TriangleMesh m, const kika::slicer::Settings& s) {
  m.transform(kika::geometry::place_on_bed(m, s.printer.bed_x / 2, s.printer.bed_y / 2));
  return m;
}

